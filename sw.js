/* Fitness de semana service worker — offline app shell + runtime cache */
const CACHE = 'fds-v18';
const ASSETS = [
  './',
  './index.html',
  './manifest.webmanifest',
  './icon-192.png',
  './icon-512.png',
  './icon-180.png',
  './icon-maskable-512.png',
  './favicon-32.png'
];

self.addEventListener('install', (e) => {
  // No se activa solo: espera a que el usuario pulse "Actualizar".
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)));
});

// La app pide el relevo cuando el usuario acepta actualizar
self.addEventListener('message', (e) => {
  if (e.data && e.data.type === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Stale-while-revalidate: sirve de caché al instante y actualiza en segundo plano.
// Cachea también las fuentes de Google en el primer uso para que funcione offline.
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  e.respondWith(
    caches.match(req).then((cached) => {
      const network = fetch(req).then((res) => {
        if (res && res.status === 200 && (res.type === 'basic' || res.type === 'cors')) {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy));
        }
        return res;
      }).catch(() => cached);
      return cached || network;
    })
  );
});
